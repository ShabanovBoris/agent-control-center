import { execFile } from 'node:child_process';
import { mkdir, readFile, rename, unlink, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { promisify } from 'node:util';

export const AUTOSTART_LABEL = 'com.agentcontrolcenter.up';
/** Маркер нашего plist: чужой файл не перезаписывается без --force. */
export const AUTOSTART_MARKER = 'generated by npm run autostart:install; do not edit';

export interface LaunchdSpec {
  label: string;
  programArguments: readonly string[];
  workingDirectory: string;
  /** PATH для launchd: минимальное окружение не находит node/openssl. */
  path: string;
  stdoutPath: string;
  stderrPath: string;
  throttleIntervalSec: number;
}

export interface LaunchdSpecOptions {
  projectRoot: string;
  execPath: string;
  keepAwake: boolean;
}

/** Стандартный PATH для launchd: минимальное окружение не находит node/openssl. */
const LAUNCHD_PATH = ['/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'];

/**
 * Тот же entrypoint, что `npm run up -- --supervised`, но напрямую: npm не пробрасывает
 * сигналы дочернему процессу. Секретов в plist нет — провайдер читается из `.local`.
 */
export function launchdSpec(options: LaunchdSpecOptions): LaunchdSpec {
  return {
    label: AUTOSTART_LABEL,
    programArguments: [
      options.execPath, '--import', 'tsx', resolve(options.projectRoot, 'scripts/up.ts'), '--supervised',
      ...(options.keepAwake ? ['--keep-awake'] : []),
    ],
    workingDirectory: options.projectRoot,
    path: [dirname(options.execPath), ...LAUNCHD_PATH].join(':'),
    stdoutPath: resolve(options.projectRoot, '.local/up.log'),
    stderrPath: resolve(options.projectRoot, '.local/up.log'),
    throttleIntervalSec: 30,
  };
}

export function escapeXml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

export function renderPlist(spec: LaunchdSpec): string {
  const array = spec.programArguments.map(argument => `    <string>${escapeXml(argument)}</string>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${AUTOSTART_MARKER} -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${escapeXml(spec.label)}</string>
  <key>ProgramArguments</key>
  <array>
${array}
  </array>
  <key>WorkingDirectory</key>
  <string>${escapeXml(spec.workingDirectory)}</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>${escapeXml(spec.path)}</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>ThrottleInterval</key>
  <integer>${spec.throttleIntervalSec}</integer>
  <key>StandardInPath</key>
  <string>/dev/null</string>
  <key>StandardOutPath</key>
  <string>${escapeXml(spec.stdoutPath)}</string>
  <key>StandardErrorPath</key>
  <string>${escapeXml(spec.stderrPath)}</string>
  <key>Umask</key>
  <integer>63</integer>
</dict>
</plist>
`;
}

export interface CommandResult {
  code: number;
  stdout: string;
  stderr: string;
}

export type LaunchdRun = (command: string, args: readonly string[]) => Promise<CommandResult>;

export interface LaunchdFs {
  read(path: string): Promise<string | undefined>;
  write(path: string, data: string, mode: number): Promise<void>;
  rename(from: string, to: string): Promise<void>;
  unlink(path: string): Promise<void>;
  mkdir(path: string): Promise<void>;
}

export interface LaunchdDeps {
  fs: LaunchdFs;
  run: LaunchdRun;
  wait(ms: number): Promise<void>;
  uid: number;
  launchctl: string;
  plutil: string;
  /** Ожидание появления/исчезновения job. */
  jobWaitMs: number;
  /** Ожидание освобождения портов после uninstall. */
  portWaitMs: number;
}

const execFileAsync = promisify(execFile);

const nodeFs: LaunchdFs = {
  async read(path) {
    try { return await readFile(path, 'utf8'); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; }
  },
  async write(path, data, mode) { await writeFile(path, data, { mode }); },
  async rename(from, to) { await rename(from, to); },
  async unlink(path) {
    try { await unlink(path); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  },
  async mkdir(path) { await mkdir(path, { recursive: true, mode: 0o700 }); },
};

async function runCommand(command: string, args: readonly string[]): Promise<CommandResult> {
  try {
    const { stdout, stderr } = await execFileAsync(command, [...args], { timeout: 30_000, maxBuffer: 8 * 1024 * 1024 });
    return { code: 0, stdout, stderr };
  } catch (error) {
    const failure = error as { code?: unknown; stdout?: string; stderr?: string; message?: string };
    return {
      code: typeof failure.code === 'number' ? failure.code : 1,
      stdout: failure.stdout ?? '',
      stderr: failure.stderr ?? failure.message ?? String(error),
    };
  }
}

export function defaultLaunchdDeps(options: Partial<LaunchdDeps> = {}): LaunchdDeps {
  return {
    fs: nodeFs,
    run: runCommand,
    wait: ms => delay(ms),
    uid: typeof process.getuid === 'function' ? process.getuid() : 0,
    launchctl: '/bin/launchctl',
    plutil: '/usr/bin/plutil',
    jobWaitMs: 30_000,
    portWaitMs: 15_000,
    ...options,
  };
}

export interface JobInfo {
  loaded: boolean;
  state?: string;
  pid?: number;
  lastExitCode?: number;
  raw?: string;
}

export async function launchdJobInfo(label: string, deps: LaunchdDeps): Promise<JobInfo> {
  const result = await deps.run(deps.launchctl, ['print', `gui/${deps.uid}/${label}`]);
  if (result.code !== 0) return { loaded: false };
  const state = /^\s*state = (.+)$/m.exec(result.stdout)?.[1]?.trim();
  const pidText = /^\s*pid = (\d+)$/m.exec(result.stdout)?.[1];
  const lastExit = /^\s*last exit code = (-?\d+)$/m.exec(result.stdout)?.[1];
  return {
    loaded: true,
    ...(state ? { state } : {}),
    ...(pidText ? { pid: Number(pidText) } : {}),
    ...(lastExit ? { lastExitCode: Number(lastExit) } : {}),
    raw: result.stdout,
  };
}

const target = (label: string, deps: LaunchdDeps): string => `gui/${deps.uid}/${label}`;

async function waitUntil<T>(deps: LaunchdDeps, timeoutMs: number, check: () => Promise<T | undefined>): Promise<T | undefined> {
  const deadline = Date.now() + timeoutMs;
  while (true) {
    const value = await check();
    if (value !== undefined) return value;
    if (Date.now() >= deadline) return undefined;
    await deps.wait(250);
  }
}

async function waitJobRunning(label: string, deps: LaunchdDeps): Promise<boolean> {
  const job = await waitUntil(deps, deps.jobWaitMs, async () => {
    const info = await launchdJobInfo(label, deps);
    return info.loaded && info.state === 'running' ? info : undefined;
  });
  return job !== undefined;
}

async function waitJobAbsent(label: string, deps: LaunchdDeps): Promise<boolean> {
  const absent = await waitUntil(deps, deps.jobWaitMs, async () => {
    const info = await launchdJobInfo(label, deps);
    return info.loaded ? undefined : true;
  });
  return absent === true;
}

export interface InstallOptions {
  spec: LaunchdSpec;
  plistPath: string;
  force?: boolean;
  deps: LaunchdDeps;
}

export interface InstallResult {
  changed: boolean;
  running: boolean;
  /** Установка отклонена без изменений: нужен --force. */
  refused?: boolean;
  messages: string[];
}

/**
 * Идемпотентная установка: одинаковый plist не переписывается и не бутстрапится
 * повторно. Загруженный, но остановленный job поднимается `kickstart` без `-k`,
 * чтобы не убивать активный ход.
 */
export async function installLaunchdJob(options: InstallOptions): Promise<InstallResult> {
  const { spec, plistPath, deps } = options;
  const rendered = renderPlist(spec);
  const existing = await deps.fs.read(plistPath);
  if (existing !== undefined && !existing.includes(AUTOSTART_MARKER) && !options.force) {
    throw new Error(`${plistPath} создан не этой командой. Проверьте файл или повторите с --force.`);
  }
  const job = await launchdJobInfo(spec.label, deps);

  if (existing !== undefined && existing !== rendered && job.loaded && job.state === 'running' && !options.force) {
    // bootout погасит up (и backend/Vite) — активные ходы прервутся без подтверждения.
    return {
      changed: false,
      running: true,
      refused: true,
      messages: [
        'plist отличается от текущей сборки (например, после обновления Node или смены флагов), а job работает.',
        'Установка выгрузит job и перезапустит up, прервав активные ходы. Остановите ходы и повторите с --force.',
      ],
    };
  }

  if (existing === rendered) {
    if (job.loaded && job.state === 'running') {
      return { changed: false, running: true, messages: [`Автозапуск уже установлен: job ${spec.label} работает (pid ${job.pid ?? '?'}).`] };
    }
    if (job.loaded) {
      const result = await deps.run(deps.launchctl, ['kickstart', target(spec.label, deps)]);
      if (result.code !== 0) throw new Error(`launchctl kickstart: ${result.stderr || result.stdout}`);
      const running = await waitJobRunning(spec.label, deps);
      return {
        changed: false,
        running,
        messages: [running
          ? `Job ${spec.label} был загружен, но не работал: выполнен kickstart.`
          : `Job ${spec.label} загружен, но не перешёл в running. Проверьте .local/up.log.`],
      };
    }
    const enabled = await deps.run(deps.launchctl, ['enable', target(spec.label, deps)]);
    if (enabled.code !== 0) throw new Error(`launchctl enable: ${enabled.stderr || enabled.stdout}`);
    const boot = await deps.run(deps.launchctl, ['bootstrap', `gui/${deps.uid}`, plistPath]);
    if (boot.code !== 0) throw new Error(`launchctl bootstrap: ${boot.stderr || boot.stdout}`);
    const running = await waitJobRunning(spec.label, deps);
    return {
      changed: false,
      running,
      messages: [running ? `Job ${spec.label} загружен и запущен.` : `Job ${spec.label} загружен, но не перешёл в running. Проверьте .local/up.log.`],
    };
  }

  // Сначала lint во временном файле: невалидный plist не должен попасть на место рабочего.
  const temp = `${plistPath}.tmp`;
  await deps.fs.write(temp, rendered, 0o600);
  const lint = await deps.run(deps.plutil, ['-lint', temp]);
  if (lint.code !== 0) {
    await deps.fs.unlink(temp);
    throw new Error(`plutil -lint отклонил plist: ${lint.stderr || lint.stdout}`);
  }
  // bootout до rename: при сбое выгрузки старый plist остаётся, и повтор снова увидит различие.
  if (job.loaded) {
    const out = await deps.run(deps.launchctl, ['bootout', target(spec.label, deps)]);
    if (out.code !== 0) {
      await deps.fs.unlink(temp);
      throw new Error(`launchctl bootout: ${out.stderr || out.stdout}`);
    }
    if (!await waitJobAbsent(spec.label, deps)) {
      await deps.fs.unlink(temp);
      throw new Error(`Job ${spec.label} не выгрузился за отведённое время; plist не изменён.`);
    }
  }
  await deps.fs.mkdir(dirname(plistPath));
  await deps.fs.rename(temp, plistPath);
  const enabled = await deps.run(deps.launchctl, ['enable', target(spec.label, deps)]);
  if (enabled.code !== 0) throw new Error(`launchctl enable: ${enabled.stderr || enabled.stdout}`);
  const boot = await deps.run(deps.launchctl, ['bootstrap', `gui/${deps.uid}`, plistPath]);
  if (boot.code !== 0) throw new Error(`launchctl bootstrap: ${boot.stderr || boot.stdout}`);
  const running = await waitJobRunning(spec.label, deps);
  return {
    changed: true,
    running,
    messages: [running
      ? `Автозапуск установлен: ${plistPath}, job ${spec.label} запущен.`
      : `Автозапуск установлен: ${plistPath}. Job загружен, но не перешёл в running; проверьте .local/up.log.`],
  };
}

export interface UninstallOptions {
  plistPath: string;
  force?: boolean;
  deps: LaunchdDeps;
  ports: readonly { port: number; host: string }[];
  portFree(port: number, host: string): Promise<boolean>;
  isAlive(pid: number): boolean;
}

export interface UninstallResult {
  changed: boolean;
  messages: string[];
}

/**
 * Снимает job и дожидается фактического выхода `up` и освобождения портов.
 * Плист удаляется только после исчезновения job: иначе состояние необратимо.
 */
export async function uninstallLaunchdJob(options: UninstallOptions): Promise<UninstallResult> {
  const { plistPath, deps } = options;
  const existing = await deps.fs.read(plistPath);
  if (existing !== undefined && !existing.includes(AUTOSTART_MARKER) && !options.force) {
    throw new Error(`${plistPath} создан не этой командой. Проверьте файл или повторите с --force.`);
  }
  const job = await launchdJobInfo(AUTOSTART_LABEL, deps);
  if (existing === undefined && !job.loaded) {
    return { changed: false, messages: ['Автозапуск не установлен: ни plist, ни job не найдены.'] };
  }
  const rememberedPid = job.pid;
  const messages: string[] = [];
  if (job.loaded) {
    const out = await deps.run(deps.launchctl, ['bootout', target(AUTOSTART_LABEL, deps)]);
    if (out.code !== 0) throw new Error(`launchctl bootout: ${out.stderr || out.stdout}`);
    if (!await waitJobAbsent(AUTOSTART_LABEL, deps)) {
      throw new Error(`Job ${AUTOSTART_LABEL} не выгрузился за отведённое время; plist оставлен на месте.`);
    }
    messages.push(`Job ${AUTOSTART_LABEL} выгружен.`);
  }
  if (rememberedPid !== undefined) {
    const exited = await waitUntil(deps, deps.jobWaitMs, async () => options.isAlive(rememberedPid) ? undefined : true);
    if (exited !== true) {
      throw new Error(`Процесс up (pid ${rememberedPid}) ещё жив после выгрузки job; plist оставлен на месте.`);
    }
    messages.push(`Процесс up (pid ${rememberedPid}) завершился.`);
  }
  if (existing !== undefined) {
    await deps.fs.unlink(plistPath);
    messages.push(`Удалён ${plistPath}.`);
  }
  const busy: string[] = [];
  for (const { port, host } of options.ports) {
    const free = await waitUntil(deps, deps.portWaitMs, async () => await options.portFree(port, host) ? true : undefined);
    if (free !== true) busy.push(String(port));
  }
  if (busy.length > 0) {
    throw new Error(`Автозапуск снят, но порты всё ещё заняты: ${busy.join(', ')}. Проверьте lsof -nP -iTCP:${busy.join(',')} -sTCP:LISTEN: возможно, работает ручной up.`);
  }
  messages.push('Порты свободны.');
  messages.push('Журналы и up-state.json не удалены: их можно убрать вручную.');
  return { changed: true, messages };
}

export interface LaunchdStatus {
  plistExists: boolean;
  ours: boolean;
  lint?: { ok: boolean; message: string };
  job: JobInfo;
  /** Совпадает ли plist с текущей сборкой (путь node, флаги, шаблон). */
  matchesSpec?: boolean;
}

export async function launchdStatus(options: { plistPath: string; deps: LaunchdDeps; spec?: LaunchdSpec }): Promise<LaunchdStatus> {
  const { plistPath, deps } = options;
  const existing = await deps.fs.read(plistPath);
  const job = await launchdJobInfo(AUTOSTART_LABEL, deps);
  if (existing === undefined) return { plistExists: false, ours: false, job };
  const lint = await deps.run(deps.plutil, ['-lint', plistPath]);
  return {
    plistExists: true,
    ours: existing.includes(AUTOSTART_MARKER),
    lint: { ok: lint.code === 0, message: (lint.stderr || lint.stdout).trim() },
    job,
    ...(options.spec ? { matchesSpec: existing === renderPlist(options.spec) } : {}),
  };
}
